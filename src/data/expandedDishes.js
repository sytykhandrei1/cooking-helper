const allergenRules = {
  'яйца': ['яйца', 'майонез'],
  'молочные продукты': ['молоко', 'кефир', 'сливки', 'сметана', 'сыр', 'творог', 'йогурт', 'сливочное масло'],
  'глютен': ['мука', 'хлеб', 'паста', 'лапша', 'булгур', 'кускус', 'перловка', 'овсяные хлопья'],
  'рыба': ['лосось', 'форель', 'треска', 'хек', 'скумбрия', 'дорада', 'судак', 'тунец'],
  'морепродукты': ['креветки', 'кальмары', 'мидии', 'гребешки'],
  'орехи': ['орехи', 'миндаль', 'арахис', 'кешью'],
  'соя': ['тофу', 'соевый соус', 'терияки'],
  'кунжут': ['кунжут', 'тахини'],
};

const detectAllergens = ingredients => Object.entries(allergenRules)
  .filter(([, markers]) => markers.some(marker => ingredients.some(item => item.includes(marker))))
  .map(([allergen]) => allergen);

const createDish = ({ name, description, ingredients, steps, category, forChildren = true, complete = true }) => ({
  id: nextId++,
  name,
  description,
  ingredients: [...new Set([...ingredients, 'соль'])],
  recipe: steps.map((step, index) => `${index + 1}. ${step}`).join(' '),
  forChildren,
  allergens: detectAllergens(ingredients),
  category,
  sideDishes: [],
  isCompleteDish: complete,
});

